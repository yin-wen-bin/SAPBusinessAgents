"""Reviewed service semantics. Never accept model-supplied mappings or proofs.

An empty registry is deliberately fail closed: metadata establishes field
existence, not business equivalence or historical configuration validity.
"""
import copy
import json
from pathlib import Path
from .runtime_contract import RuntimeContractError

PATH = Path(__file__).resolve().parents[2] / 'config/runtime-evidence-bindings.json'
VERSION = 'sapba.evidence-bindings/1'


def registry():
    value = json.loads(PATH.read_text(encoding='utf-8'))
    allowed = {'version', 'scope_mappings', 'configuration_sources'}
    if value.get('version') == 'sapba.evidence-bindings/2':
        allowed.add('relations')
    if (value.get('version') not in {VERSION, 'sapba.evidence-bindings/2'} or set(value) != allowed
            or not isinstance(value['scope_mappings'], list) or not isinstance(value['configuration_sources'], list)):
        raise ValueError('runtime_evidence_registry_invalid')
    # These are deployment-reviewed records, not candidates generated by an SDK.
    for record in value['scope_mappings'] + value['configuration_sources']:
        if not isinstance(record, dict) or not record.get('review_reference'):
            raise ValueError('runtime_evidence_registry_unreviewed')
        if not all(isinstance(record.get(k), str) and record[k] for k in ('service_name', 'odata_version', 'entity_set')):
            raise ValueError('runtime_evidence_registry_invalid')
    for record in value['configuration_sources']:
        if record.get('kind') not in {None, 'adt-posted-item-classification/1'}:
            raise ValueError('runtime_evidence_registry_invalid')
        if record.get('kind') and (record.get('skill_id') != 'sap-adt-table-export' or set(record) != {
                'kind','service_name','odata_version','entity_set','skill_id','review_reference'}):
            raise ValueError('runtime_evidence_registry_invalid')
    if 'relations' in value:
        from .runtime_relations import validate_rules
        validate_rules(value['relations'])
    return copy.deepcopy(value)


def scope_fields(records, step, names, fields):
    """Return exact entity-scoped equivalence groups only after metadata proof."""
    result = tuple(names)
    for record in records:
        if (all(record.get(k) == step.get(k) for k in ('service_name', 'odata_version', 'entity_set'))
                and tuple(record.get('canonical_fields', ())) == tuple(names)):
            mapped = record.get('entity_fields')
            if not isinstance(mapped, list) or not mapped or fields is None or not set(mapped) <= fields:
                raise ValueError('runtime_scope_mapping_schema_mismatch')
            if result != tuple(names) and result != tuple(mapped):
                raise ValueError('runtime_scope_mapping_ambiguous')
            result = tuple(mapped)
    return result


def configuration_rows(record, rows, *, evidence_ref, source_plan):
    """Decode only a registered complete source; caller proves ownership first.

    No current-to-historical inference, system fallback, bool coercion or code
    guessing. Dates and classification contradictions remain assessor errors.
    """
    if not all(record.get(k) == source_plan.get(k) for k in ('service_name', 'odata_version', 'entity_set')):
        raise RuntimeContractError('source_configuration_source_mismatch')
    mapping = record.get('fields') or {}
    required = {'account_type', 'code', 'noted_item', 'valid_from', 'valid_to', 'company_code'}
    if set(mapping) != required or len(set(mapping.values())) != len(mapping):
        raise RuntimeContractError('source_configuration_mapping_invalid')
    result = []
    for row in rows:
        if not isinstance(row, dict) or any(field not in row for field in mapping.values()):
            raise RuntimeContractError('source_configuration_evidence_incomplete')
        value = {name: row[field] for name, field in mapping.items()}
        if type(value['noted_item']) is not bool or any(not isinstance(value[k], str) or not value[k]
                for k in required - {'noted_item'}):
            raise RuntimeContractError('source_configuration_evidence_invalid')
        result.append({**value, 'verified': True, 'evidence_ref': evidence_ref})
    return result
